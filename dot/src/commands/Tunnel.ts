import { join } from "node:path";
import {
  Clock,
  Console,
  Deferred,
  Duration,
  Effect,
  Fiber,
  FileSystem,
  Option,
  Ref,
  Schema,
} from "effect";
import { FetchHttpClient, HttpClient } from "effect/http";
import { ChildProcess, ChildProcessSpawner } from "effect/process";
import { CommandExecutor, exitStatus } from "../services/CommandExecutor.js";
import { CONFIG_DIR, STATE_DIR } from "../lib/paths.js";
import { type ReportedStatus, writeReportedStatus } from "./Services.js";

/** A tunnel's credentials or Cloudflare's view of its connectors are unavailable. */
export class TunnelError extends Schema.TaggedError<TunnelError>()(
  "TunnelError",
  { message: Schema.String },
) {}

/** Tunnel tokens (`<name>.token`) and the shared Cloudflare API token. */
const TUNNELS_DIR = join(CONFIG_DIR, "dot", "tunnels");

const API_TOKEN_FILE = join(TUNNELS_DIR, "cloudflare-api-token");

const CHECK_INTERVAL = Duration.seconds(15);

// Spreads the checks of machines that started together, so they don't keep
// starting and stopping in step.
const CHECK_JITTER_MILLIS = 5_000;

const REQUEST_TIMEOUT = "10 seconds";

/** The account and tunnel IDs inside a base64 tunnel token. */
const TunnelToken = Schema.fromJsonString(
  Schema.Struct({ a: Schema.NonEmptyString, t: Schema.NonEmptyString }),
);

const ConnectionsResponse = Schema.Struct({
  success: Schema.Boolean,
  errors: Schema.Array(Schema.Struct({ message: Schema.String })),
  result: Schema.NullOr(
    Schema.Array(
      Schema.Struct({
        id: Schema.String,
        conns: Schema.Array(
          Schema.Struct({
            opened_at: Schema.String,
            is_pending_reconnect: Schema.optionalKey(Schema.Boolean),
          }),
        ),
      }),
    ),
  ),
});

const ReadyResponse = Schema.Struct({ connectorId: Schema.String });

/** A cloudflared instance with live connections to the tunnel. */
interface Connector {
  /** Connector ID, generated by cloudflared each time it starts. */
  readonly id: string;
  /** When its oldest live connection opened, in epoch milliseconds. */
  readonly since: number;
}

/** The cloudflared this machine runs, and the port of its metrics server. */
interface Running {
  readonly fiber: Fiber.Fiber<number, unknown>;
  readonly port: number;
}

const formatTime = (millis: number) =>
  new Date(millis).toLocaleTimeString("en-GB", {
    hour: "2-digit",
    minute: "2-digit",
  });

const heldBy = (connectors: readonly Connector[]) =>
  `Held by another machine since ${formatTime(Math.min(...connectors.map((connector) => connector.since)))}`;

/** Whether `other` connected first, so it keeps the tunnel over `self`. */
const connectedFirst = (other: Connector, self: Connector) =>
  other.since < self.since ||
  (other.since === self.since && other.id < self.id);

const freePort = Effect.sync(() => {
  const listener = Bun.listen({
    hostname: "127.0.0.1",
    port: 0,
    socket: { data() {} },
  });

  const { port } = listener;
  listener.stop(true);

  return port;
});

/**
 * Run a Cloudflare tunnel on one machine at a time.
 *
 * Every machine that runs a tunnel shares its token, and Cloudflare spreads
 * traffic across all their connectors. This keeps one: the connector that
 * connected first holds the tunnel, and any other stops its cloudflared and
 * waits, reporting a warning to `dot services`, until no connector is left.
 * A machine that wakes from sleep reconnects later than whoever took over, so
 * it gives the tunnel back.
 */
export const tunnelRun = Effect.fn("Tunnel.run")(
  function* (name: string) {
    if (!/^[\w-]+$/.test(name))
      return yield* new TunnelError({ message: `Invalid tunnel name ${name}` });

    const fs = yield* FileSystem.FileSystem;
    const spawner = yield* ChildProcessSpawner.ChildProcessSpawner;
    const executor = yield* CommandExecutor;
    const http = yield* HttpClient.HttpClient;
    const tokenFile = join(TUNNELS_DIR, `${name}.token`);
    const statusFile = join(STATE_DIR, "dot", "tunnels", name, "status.json");
    const stop = yield* Deferred.make<void>();
    const running = yield* Ref.make<Option.Option<Running>>(Option.none());

    const lastReport = yield* Ref.make<Option.Option<ReportedStatus>>(
      Option.none(),
    );

    const refreshPanel = executor
      .exitCode("omarchy-shell", ["-q", "timmo.services", "refresh"])
      .pipe(Effect.ignore);

    const onSignal = () => Deferred.doneUnsafe(stop, Effect.void);

    yield* Effect.acquireRelease(
      Effect.sync(() => {
        process.on("SIGINT", onSignal);
        process.on("SIGTERM", onSignal);
        process.on("SIGHUP", onSignal);
      }),
      () =>
        Effect.sync(() => {
          process.off("SIGINT", onSignal);
          process.off("SIGTERM", onSignal);
          process.off("SIGHUP", onSignal);
        }),
    );

    const report = Effect.fn("Tunnel.report")(function* (
      health: ReportedStatus["health"],
      summary: string,
    ) {
      const previous = Option.getOrUndefined(yield* Ref.get(lastReport));

      const status = {
        health,
        summary,
        updated: yield* Clock.currentTimeMillis,
      } satisfies ReportedStatus;

      yield* writeReportedStatus(statusFile, status).pipe(
        Effect.catch((error) =>
          Console.error(
            `[WARN] Could not write ${statusFile}: ${error.message}`,
          ),
        ),
      );
      yield* Ref.set(lastReport, Option.some(status));

      if (previous?.summary !== summary)
        yield* Console.log(`[${health.toUpperCase()}] ${summary}`);

      if (previous?.health !== health) yield* refreshPanel;
    });

    const readSecret = (path: string) =>
      fs.readFileString(path).pipe(
        Effect.map((text) => text.trim()),
        Effect.filterOrFail(
          (text) => text.length > 0,
          () => new TunnelError({ message: `${path} is empty` }),
        ),
        Effect.mapError(
          (error) =>
            new TunnelError({
              message:
                error instanceof TunnelError ? error.message : `No ${path}`,
            }),
        ),
      );

    const listConnectors = Effect.gen(function* () {
      const token = yield* readSecret(tokenFile);
      const apiToken = yield* readSecret(API_TOKEN_FILE);

      const ids = yield* Schema.decodeEffect(TunnelToken)(
        Buffer.from(token, "base64").toString(),
      ).pipe(
        Effect.mapError(
          () => new TunnelError({ message: `Invalid token in ${tokenFile}` }),
        ),
      );

      const body = yield* http
        .get(
          `https://api.cloudflare.com/client/v4/accounts/${ids.a}/cfd_tunnel/${ids.t}/connections`,
          { headers: { authorization: `Bearer ${apiToken}` } },
        )
        .pipe(
          Effect.flatMap((response) => response.json),
          Effect.timeout(REQUEST_TIMEOUT),
          Effect.flatMap(Schema.decodeUnknownEffect(ConnectionsResponse)),
          Effect.mapError(
            () =>
              new TunnelError({
                message: "Could not reach the Cloudflare API",
              }),
          ),
        );

      if (!body.success || body.result === null)
        return yield* new TunnelError({
          message: `Cloudflare API: ${body.errors.map((error) => error.message).join("; ") || "request failed"}`,
        });

      return body.result.flatMap((connector): Connector[] => {
        const opened = connector.conns
          .filter((conn) => conn.is_pending_reconnect !== true)
          .map((conn) => Date.parse(conn.opened_at))
          .filter(Number.isFinite);

        return opened.length > 0
          ? [{ id: connector.id, since: Math.min(...opened) }]
          : [];
      });
    }).pipe(Effect.withSpan("Tunnel.listConnectors"));

    const ownConnectorId = (port: number) =>
      http.get(`http://127.0.0.1:${port}/ready`).pipe(
        Effect.flatMap((response) => response.json),
        Effect.flatMap(Schema.decodeUnknownEffect(ReadyResponse)),
        Effect.timeout(REQUEST_TIMEOUT),
        Effect.map((ready) => Option.some(ready.connectorId)),
        Effect.orElseSucceed(() => Option.none<string>()),
      );

    const start = Effect.gen(function* () {
      const port = yield* freePort;

      const fiber = yield* spawner
        .spawn(
          ChildProcess.make(
            "cloudflared",
            [
              "tunnel",
              "--no-autoupdate",
              "--metrics",
              `127.0.0.1:${port}`,
              "run",
              "--token-file",
              tokenFile,
            ],
            {
              stdin: "ignore",
              stdout: "inherit",
              stderr: "inherit",
              forceKillAfter: 5_000,
            },
          ),
        )
        .pipe(Effect.flatMap(exitStatus), Effect.scoped, Effect.forkScoped);

      yield* Ref.set(running, Option.some({ fiber, port }));
    }).pipe(Effect.withSpan("Tunnel.start"));

    const stopCloudflared = Effect.gen(function* () {
      const current = yield* Ref.getAndSet(running, Option.none());

      if (Option.isSome(current)) yield* Fiber.interrupt(current.value.fiber);
    }).pipe(Effect.withSpan("Tunnel.stop"));

    const check = Effect.gen(function* () {
      const current = yield* Ref.get(running);
      const exited = Option.isSome(current) && current.value.fiber.pollUnsafe();

      if (exited) {
        yield* Ref.set(running, Option.none());
        yield* Console.error("[WARN] cloudflared exited");
      }

      const connectors = yield* listConnectors;
      const state = yield* Ref.get(running);

      if (Option.isNone(state)) {
        if (connectors.length > 0)
          return yield* report("warning", heldBy(connectors));

        yield* start;

        return yield* report("ok", "Taking over the tunnel");
      }

      const own = yield* ownConnectorId(state.value.port);

      const mine = connectors.find((connector) =>
        Option.contains(own, connector.id),
      );

      const others = connectors.filter(
        (connector) => !Option.contains(own, connector.id),
      );

      const first = mine
        ? others.filter((other) => connectedFirst(other, mine))
        : others;

      if (first.length > 0) {
        yield* stopCloudflared;

        return yield* report("warning", heldBy(first));
      }

      yield* mine
        ? report("ok", `Serving since ${formatTime(mine.since)}`)
        : report("ok", "Connecting");
    }).pipe(
      Effect.catchTag("TunnelError", (error) =>
        Effect.gen(function* () {
          const serving = Option.isSome(yield* Ref.get(running));

          yield* report(
            "warning",
            serving
              ? `${error.message}; still serving`
              : `${error.message}; not taking over`,
          );
        }),
      ),
      Effect.withSpan("Tunnel.check"),
    );

    yield* Effect.addFinalizer(() =>
      Effect.gen(function* () {
        yield* stopCloudflared;
        yield* fs.remove(statusFile, { force: true }).pipe(Effect.ignore);
        yield* refreshPanel;
      }),
    );

    yield* Console.log(`Running tunnel ${name}`);

    yield* Effect.raceFirst(
      check.pipe(
        Effect.andThen(
          Effect.suspend(() =>
            Effect.sleep(
              Duration.sum(
                CHECK_INTERVAL,
                Duration.millis(Math.random() * CHECK_JITTER_MILLIS),
              ),
            ),
          ),
        ),
        Effect.forever,
      ),
      Deferred.await(stop),
    );
  },
  Effect.scoped,
  Effect.provide(FetchHttpClient.layer),
);
